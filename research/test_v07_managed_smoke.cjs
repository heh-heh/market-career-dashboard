for(const m of html.matchAll(/<script(?:\s[^>]*)?>([\s\S]*?)<\/script>/g))new vm.Script(m[1]);
const panel=html.slice(html.indexOf('<!-- V07_MANAGED_CARD_BEGIN -->'),html.indexOf('<!-- V07_MANAGED_CARD_END -->'));
