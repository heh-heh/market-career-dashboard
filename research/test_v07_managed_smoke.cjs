assert.match(html,/setNotice\(cmd\+" · 실행 요청 차단 또는 실패:/,'rejected launches must be visible on AI tab');
assert.match(html,/setNotice\(cmd\+" · 서버 응답:/,'accepted launches must be visible on AI tab');
